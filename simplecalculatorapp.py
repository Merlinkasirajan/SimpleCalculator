# 1. Import Streamlit library
import streamlit as st

# 2. Define Python functions
def addition(a, b):
    return a + b

def subtraction(a, b):
    return a - b

def multiplication(a, b):
    return a * b

# 3. Create application title and instructions
st.title("Simple Calculator")
st.write("Enter two numbers and select an operation.")

# 4. Create user input fields
a = st.number_input("First number")
b = st.number_input("Second number")

# 5. Create dropdown menu
operation = st.selectbox(
    "Choose an operation",
    ["Addition", "Subtraction", "Multiplication"]
)

# 6. Create button and perform calculation
if st.button("Calculate"):

    if operation == "Addition":
        result = addition(a, b)

    elif operation == "Subtraction":
        result = subtraction(a, b)

    elif operation == "Multiplication":
        result = multiplication(a, b)

    # 7. Display the result
    st.success(f"Result: {result}")
